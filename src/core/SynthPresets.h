#pragma once
// Built-in named synth presets for the SYNTH tab's PRESET browse row (see
// ui/SynthView.cpp, toggled with X+Y same as FxView's TRACK SENDS/MASTER
// FX and the Piano Roll's sound-design overlay) -- a curated starting
// point for each of the 3 monophonic SubtractiveSynth voices, instead of
// hand-dialing all 15 SynthPatch knobs (WAVEFORM..LFO SHAPE, see
// ui/SynthParams.cpp) from the flat Saw-4kHz default every time.
//
// Each preset below is a full SynthPatch (every field the engine actually
// has -- oscillator waveform, filter cutoff/resonance/envelope, amp
// envelope, glide, volume, and the Phase 3 automation LFO), mapped from
// genuine, researched sound-design conventions for that style of patch
// (TB-303 acid bass, techno stabs, pads, dubstep wobble bass, reese bass,
// sub bass, plucks, brass stabs, trance gating, ambient drones -- see the
// per-preset comments in SynthPresets.cpp for what each one is grounded
// in). This is a SINGLE monophonic oscillator with one filter and one
// free-running LFO, not a multi-oscillator/unison synth -- a couple of
// presets (REESE BASS especially, which classically needs two detuned
// oscillators) are honest APPROXIMATIONS of the real technique adapted to
// what this engine can actually do (e.g. a slow, shallow pitch-LFO
// standing in for the "beating" of a second detuned oscillator), not a
// literal reproduction. Same "genre-style, not a transcription" honesty
// DrumPatterns.h/DrumBreaks.h already use for their genre-shaped content.
//
// Deliberately a separate, smaller data set from CustomSynthPresets.h's
// user-saved presets (compiled in here vs. read from "presets/*.t8syn" on
// disk) -- same GenrePattern/DrumBreak (built-in, compiled) vs.
// CustomPatterns (user-saved, on disk) split already established for drum
// patterns, and SynthView's PRESET row browses a single combined list of
// both the same way TYPICAL PATTERN does (see AppState::ApplySynthPreset).
#include "Types.h"
#include <string>
#include <vector>

namespace t8 {

struct SynthPresetData {
    const char* name;
    const char* category;   // one of kSynthCategories
    SynthPatch patch;
};

constexpr int kNumSynthCategories = 6;
extern const char* const kSynthCategories[kNumSynthCategories];   // BASS LEAD PAD KEYS PLUCK FX (saved presets are MY)

// 10 original SubtractiveSynth presets, 3 Phase 5 FM presets (FM
// BELL/EPIANO/BASS -- see SynthPresets.cpp) demonstrating a few of
// FMSynth's 4 fixed algorithms with classic, well-established FM
// sound-design conventions (inharmonic operator ratios for bells,
// fast-transient 2-op-style patches for electric piano, sub-harmonic
// modulator stacking for growl bass), and 3 Phase 5b Wavetable presets
// (WT SWEEP PAD/PWM LEAD/VOWEL BASS) demonstrating position-scanning
// across a couple of the 4 built-in wavetable banks -- same "genre-style,
// not a literal transcription" honesty as the subtractive presets above.
// v44: the library (about 55 presets) is built once; AllSynthPresets().size() is the count. Every preset carries a category and a level
// (SynthPresetLevels.inc, generated by t8_presetaudit --write-levels).
const std::vector<SynthPresetData>& AllSynthPresets();

// Tags a browser can filter by, derived from the patch itself: UNI SUB OSC2 ACID / 24dB LFO FM WT.
std::vector<std::string> PresetTags(const SynthPatch& p);

} // namespace t8
